// Package catalogen renders docs/architecture/events.yaml (the event catalog, ARC-04) as Go source.
// Used by `go generate` in internal/platform/events and by that package's drift test.
package catalogen

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"sort"

	"go.yaml.in/yaml/v3"
)

type doc struct {
	Events []struct {
		Name     string   `yaml:"name"`
		Producer string   `yaml:"producer"`
		Data     []string `yaml:"data"`
	} `yaml:"events"`
}

// Render reads the catalog at path and returns the formatted catalog.gen.go source.
func Render(path string) ([]byte, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var d doc
	if err := yaml.Unmarshal(raw, &d); err != nil {
		return nil, fmt.Errorf("catalogen: parse %s: %w", path, err)
	}
	sort.Slice(d.Events, func(i, j int) bool { return d.Events[i].Name < d.Events[j].Name })

	var b bytes.Buffer
	b.WriteString("// Code generated by internal/platform/events/internal/catalogen from docs/architecture/events.yaml. DO NOT EDIT.\n\n")
	b.WriteString("package events\n\n")
	b.WriteString("// Catalog maps every event type in docs/architecture/events.yaml to its producer module and\n")
	b.WriteString("// the fields its data must carry.\n")
	b.WriteString("var Catalog = map[string]Spec{\n")
	seen := map[string]bool{}
	for _, e := range d.Events {
		if e.Name == "" || e.Producer == "" {
			return nil, fmt.Errorf("catalogen: event without name or producer in %s", path)
		}
		if seen[e.Name] {
			return nil, fmt.Errorf("catalogen: duplicate event %q", e.Name)
		}
		seen[e.Name] = true
		fmt.Fprintf(&b, "\t%q: {Producer: %q, Data: %#v},\n", e.Name, e.Producer, e.Data)
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}
